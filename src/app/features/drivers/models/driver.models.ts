import { DriverStatus } from '@core/constants/enums';
import { DriverCredentials, DriverDto } from '@core/models/domain.models';

/**
 * URL-backed list filters (`GET /drivers`). Empty string = "any".
 * A `type` (not an interface) so it satisfies `injectUrlState`'s record constraint.
 */
export type DriversQuery = {
  search: string;
  status: DriverStatus | '';
  officeId: string;
  supervisorUserId: string;
  /** '' | 'true' | 'false' — text so "any" survives the URL round-trip. */
  hasActiveAssignment: '' | 'true' | 'false';
  hasAppAccess: '' | 'true' | 'false';
  sortBy: 'name' | 'status' | 'createdAt' | 'licenseExpiry' | '';
  sortDesc: boolean;
  pageIndex: number;
  pageSize: number;
};

export const DRIVERS_QUERY_DEFAULTS: DriversQuery = {
  search: '',
  status: '',
  officeId: '',
  supervisorUserId: '',
  hasActiveAssignment: '',
  hasAppAccess: '',
  sortBy: '',
  sortDesc: false,
  pageIndex: 1,
  pageSize: 20,
};

/** `PUT /drivers/{id}` (Swagger: SaveDriverRequest). */
export interface SaveDriverRequest {
  fullName: string;
  phoneNumber: string;
  nationalId?: string | null;
  licenseNumber?: string | null;
  /** DateOnly `yyyy-MM-dd`. */
  licenseExpiryDate?: string | null;
  address?: string | null;
  officeId: string;
  supervisorUserId?: string | null;
}

/** `POST /drivers` (Swagger: CreateDriverRequest). Empty password → generated by the server. */
export interface CreateDriverRequest extends SaveDriverRequest {
  password?: string | null;
}

/** `POST /drivers/{id}/status` (Swagger: ChangeDriverStatusRequest). */
export interface ChangeDriverStatusRequest {
  status: DriverStatus;
  reason?: string | null;
}

/** `POST /drivers/{id}/account` (Swagger: CreateDriverAccountRequest). */
export interface CreateDriverAccountRequest {
  password?: string | null;
}

/** `POST /drivers/{id}/reset-password` (Swagger: SetDriverPasswordRequest). */
export interface SetDriverPasswordRequest {
  newPassword?: string | null;
}

/** `POST /drivers` and `POST /drivers/{id}/account` response. */
export interface DriverWithCredentials {
  driver: DriverDto;
  credentials: DriverCredentials;
}

/** Driver page tabs (`?tab=`). */
export type DriverTab = 'info' | 'rentals' | 'documents' | 'account' | 'oil';

/** Days before licence expiry at which the list starts warning. */
export const LICENSE_WARN_DAYS = 30;
